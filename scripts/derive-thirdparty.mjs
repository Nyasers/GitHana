/**
 * 同步 SDK 第三方声明到 licenses/（它是派生的，其余正文是仓库持有的静态原文）。
 * @returns {boolean} 是否写入
 */
function syncSdkThirdParty({ check }) {
  const text = sdkThirdPartyText();
  const dest = join(LICENSES_DIR, "hana-app-sdk-THIRD_PARTY_NOTICES.txt");
  const existing = fs.existsSync(dest) ? fs.readFileSync(dest, "utf8") : null;
  if (existing === text) return false;
  if (check) {
    throw new Error(
      "licenses/hana-app-sdk-THIRD_PARTY_NOTICES.txt 与 SDK tarball 不一致（有漂移）\n" +
        "  跑 node scripts/derive-thirdparty.mjs 重新派生。",
    );
  }
  fs.mkdirSync(LICENSES_DIR, { recursive: true });
  fs.writeFileSync(dest, text, "utf8");
  return true;
}

function main() {
  const check = process.argv.includes("--check");

  // 仓库不再持有通知正文（它是包的一部分，由 pack 渲染）；这里只同步从 tgz 现取的那份声明。
  try {
    const sdkUpdated = syncSdkThirdParty({ check });
    if (sdkUpdated) console.log("[derive-thirdparty] 已写入 licenses/hana-app-sdk-THIRD_PARTY_NOTICES.txt");
    else console.log("[derive-thirdparty] SDK 第三方声明一致");
  } catch (e) {
    console.error("[derive-thirdparty]", (e && e.message) || e);
    process.exit(1);
  }
}

// 作为模块被 pack.mjs import 时不执行 CLI。
const invoked = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (invoked) main();

